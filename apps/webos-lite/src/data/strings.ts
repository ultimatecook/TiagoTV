export type StringKey = keyof typeof ES;

/** The copy for `key`, with `{{name}}` placeholders filled. */
export function t(key: StringKey, params: Readonly<Record<string, string | number>> = {}): string {
    return ES[key].replace(/\{\{\s*(\w+)\s*\}\}/g, (_, name: string) =>
        params[name] !== undefined ? String(params[name]) : ''
    );
}

/** The copy for a key the desktop's helpers name (a genre's, a row's). */
export function tKey(key: string, params: Readonly<Record<string, string | number>> = {}): string {
    return key in ES ? t(key as StringKey, params) : key;
}
